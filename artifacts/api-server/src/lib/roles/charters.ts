// ── Who does what: the charter of every role ─────────────────────
// A persona says who someone is ("صبور، لا يُلحّ"); it does not say what they
// are responsible for, when they act, what they hand over and to whom, or how
// anyone would know they did it well. A weak model given a character and no
// job improvises a job, and the improvised one is always the same: a polite,
// generic message.
//
// So every role has a charter, written once here and rendered into its
// instructions right after its persona:
//
//   department → mission in one sentence → when it acts → what it receives →
//   what it delivers → how it is measured → who it hands to, and when →
//   what is not its job
//
// Menu For You has three kinds of team, and each charter is written for the
// people that team actually serves:
//
//   a branch's team   (CORE)      the shop's own WhatsApp: its host, customer
//                                 service, follow-up and the officers who keep
//                                 the number safe — serving the shop's diners
//                                 and clients, never selling the platform;
//   the email team    (EMAIL)     the platform selling Menu For You to shops
//                                 by email — the owner's, at /email;
//   the platform's seller (PLATFORM) سارة at /admin/sales, talking to shop
//                                 owners on WhatsApp about Menu For You.
//
// The persona stays the owner's to edit; the charter is the job description,
// and is the same for every account.

